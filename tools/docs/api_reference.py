"""API reference pages for the docs site (D-01), generated from the committed OpenAPI contracts.

    uv run python -m tools.docs.api_reference      # writes docs/handbook/api/<service>.md

A test fails when the pages and the contracts disagree, so the reference never drifts. Only what
the gateway exposes is listed: internal services (authz, model-gateway), operational endpoints
and internal paths are left out.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = ROOT / "contracts" / "openapi"
OUT = ROOT / "docs" / "handbook" / "api"
INTERNAL_SERVICES = {"authz", "model-gateway"}
METHODS = ("get", "post", "put", "patch", "delete")
TITLES = {
    "identity": "Identity: organizations, members, API keys",
    "config": "Configuration: assistants, packs, profiles, versions",
    "audit": "Audit log",
    "evaluation": "Evaluations",
    "metering": "Usage, cost and insights",
    "governance": "Data export, retention and deletion",
    "notification": "Notifications and webhooks",
    "ingestion": "Knowledge ingestion",
    "retrieval": "Search and citations",
    "agent-runtime": "Assistant runs",
    "conversation": "Conversations",
    "channel": "Channels and the widget",
    "tool-gateway": "Tools and actions",
}


def public(path: str) -> bool:
    return not (
        path in ("/meta", "/healthz", "/readyz", "/v1/context")
        or "/internal/" in path
        or path.startswith("/v1/_lifecycle")
        or path.startswith("/.well-known")
    )


def schema_name(node: dict[str, Any] | None) -> str:
    if not node:
        return ""
    if "$ref" in node:
        return f"`{node['$ref'].rsplit('/', 1)[-1]}`"
    if node.get("type") == "array" and "items" in node:
        inner = schema_name(node["items"])
        return f"list of {inner}" if inner else "list"
    return str(node.get("type", ""))


def body_of(op: dict[str, Any]) -> str:
    content = (op.get("requestBody") or {}).get("content") or {}
    for media in ("application/json", "multipart/form-data", "application/yaml"):
        if media in content:
            return schema_name(content[media].get("schema")) or media
    return ""


def result_of(op: dict[str, Any]) -> str:
    for code in ("200", "201", "202"):
        r = (op.get("responses") or {}).get(code)
        if r:
            content = r.get("content") or {}
            if "text/event-stream" in content:
                return f"{code}, event stream"
            schema = schema_name((content.get("application/json") or {}).get("schema"))
            return f"{code} {schema}".strip()
    if "204" in (op.get("responses") or {}):
        return "204"
    return ""


def describe(op: dict[str, Any]) -> str:
    """The first sentence of the endpoint's description, without internal backlog ids."""
    text = " ".join((op.get("description") or op.get("summary") or "").split())
    match = re.search(r"^(.+?[.:])(\s|$)", text)
    text = (
        match.group(1).rstrip(":") + ("." if match.group(1).endswith(":") else "")
        if match
        else text
    )
    text = re.sub(r"\s*\((?:[A-Z]{1,4}-\d+[a-z]?)(?:[,;][^)]*)?\)", "", text)
    return text.replace("``", "`").replace("|", "\\|")


def page(service: str, spec: dict[str, Any]) -> str:
    title = TITLES.get(service, service)
    lines = [
        f"# {title}",
        "",
        "<!-- Generated by tools/docs/api_reference.py from contracts/openapi; do not edit. -->",
        "",
        f"Base path: `https://<gateway>/{service}`. Every call needs an API key or a Studio session "
        "(see [Authentication](index.md#authentication)). Request and response fields are in the "
        f"OpenAPI document, `contracts/openapi/{service}.json`.",
        "",
        "| Method | Path | What it does | Body | Returns |",
        "|---|---|---|---|---|",
    ]
    rows = 0
    for path, item in sorted(spec.get("paths", {}).items()):
        if not public(path):
            continue
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            summary = describe(op)
            lines.append(
                f"| `{method.upper()}` | `{path}` | {summary} | {body_of(op)} | {result_of(op)} |"
            )
            rows += 1
    if rows == 0:
        lines.append("| | | No public endpoints. | | |")
    return "\n".join(lines) + "\n"


def pages() -> dict[str, str]:
    out: dict[str, str] = {}
    for file in sorted(CONTRACTS.glob("*.json")):
        service = file.stem
        if service in INTERNAL_SERVICES:
            continue
        out[f"{service}.md"] = page(service, json.loads(file.read_text()))
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in pages().items():
        (OUT / name).write_text(text)
        print(f"wrote {OUT / name}")


if __name__ == "__main__":
    main()
