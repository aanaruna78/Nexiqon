"""Generate git-ignored local keys in deploy/compose/config:

* dev-secrets.yaml: context-token and snapshot signing keys (identity, config): control-core only
* dev-public-keys.yaml: the matching public keys, for every other group
* dev-service-keys.yaml: public keys of per-service identities, readable by every service (ADR 0017)
* dev-secrets-<service>.yaml: that service's private key, mounted into its group only

make dev-secrets
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from nexiqon_core.keys import SERVICE_IDENTITIES as INSTALLATION_IDENTITIES
from nexiqon_core.testing import make_keypair

CONFIG = Path(__file__).resolve().parents[2] / "deploy" / "compose" / "config"
OUT = CONFIG / "dev-secrets.yaml"
# The per-service identities (the same list the installation keys use).
SERVICE_IDENTITIES = INSTALLATION_IDENTITIES


def _write(path: Path, data: dict[str, object]) -> None:
    path.write_text(
        "# Generated by tools/dev/gen_dev_secrets.py. Local development only.\n"
        + yaml.safe_dump(data)
    )
    path.chmod(0o644)  # readable by the non-root container user; local dev keys only
    print(f"wrote {path}")


def service_keys(force: bool) -> None:
    """Create a key pair for every service identity that lacks one; keep the existing ones."""
    public_file = CONFIG / "dev-service-keys.yaml"
    current = (
        (yaml.safe_load(public_file.read_text()) or {})
        if public_file.exists() and not force
        else {}
    )
    tokens = current.get("context_token", {})
    public_keys: dict[str, str] = dict(tokens.get("public_keys", {}))
    mapping: dict[str, str] = dict(tokens.get("service_keys", {}))
    changed = False
    for service, settings_key in SERVICE_IDENTITIES.items():
        kid = f"svc-{service}-dev-1"
        secret_file = CONFIG / f"dev-secrets-{service}.yaml"
        if not force and secret_file.exists() and kid in public_keys:
            continue
        private_pem, public_pem = make_keypair()
        public_keys[kid], mapping[kid] = public_pem, service
        _write(secret_file, {settings_key: {"key_id": kid, "private_key": private_pem}})
        changed = True
    if changed:
        _write(
            public_file, {"context_token": {"public_keys": public_keys, "service_keys": mapping}}
        )


def public_keys() -> None:
    """dev-public-keys.yaml: what every group but control-core needs (verification only). The
    signing private keys in dev-secrets.yaml stay with identity and config (control-core)."""
    from cryptography.hazmat.primitives import serialization

    data = yaml.safe_load(OUT.read_text())
    snapshot = {}
    for kid, pem in (data.get("snapshot_signing") or {}).get("private_keys", {}).items():
        key = serialization.load_pem_private_key(pem.encode(), password=None)
        snapshot[kid] = (
            key.public_key()
            .public_bytes(
                serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
            )
            .decode()
        )
    _write(
        CONFIG / "dev-public-keys.yaml",
        {
            "context_token": {"public_keys": data["context_token"]["public_keys"]},
            # The data-plane config mirror verifies configuration snapshots with these (DV-04).
            "snapshot_public_keys": snapshot,
        },
    )


def main() -> int:
    force = "--force" in sys.argv
    service_keys(force)
    if OUT.exists() and not force:
        print(f"{OUT} exists (use --force to rotate)")
        public_keys()
        return 0
    private_pem, public_pem = make_keypair()
    snapshot_private, _ = make_keypair()
    data = {
        "signing": {"active_kid": "dev-1", "private_keys": {"dev-1": private_pem}},
        "context_token": {"public_keys": {"dev-1": public_pem}},
        "snapshot_signing": {
            "active_kid": "snap-dev-1",
            "private_keys": {"snap-dev-1": snapshot_private},
        },
    }
    _write(OUT, data)
    public_keys()
    return 0


if __name__ == "__main__":
    sys.exit(main())
