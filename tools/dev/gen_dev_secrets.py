"""Generate deploy/compose/config/dev-secrets.yaml (git-ignored): context-token and snapshot keys.

make dev-secrets
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from nexiqon_core.testing import make_keypair

OUT = Path(__file__).resolve().parents[2] / "deploy" / "compose" / "config" / "dev-secrets.yaml"


def main() -> int:
    if OUT.exists() and "--force" not in sys.argv:
        print(f"{OUT} exists (use --force to rotate)")
        return 0
    private_pem, public_pem = make_keypair()
    snapshot_private, _ = make_keypair()
    data = {
        "signing": {"active_kid": "dev-1", "private_keys": {"dev-1": private_pem}},
        "context_token": {"public_keys": {"dev-1": public_pem}},
        "snapshot_signing": {
            "active_kid": "snap-dev-1",
            "private_keys": {"snap-dev-1": snapshot_private},
        },
    }
    OUT.write_text(
        "# Generated by tools/dev/gen_dev_secrets.py. Local development only.\n"
        + yaml.safe_dump(data)
    )
    OUT.chmod(0o644)  # readable by the non-root container user; local dev keys only
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
