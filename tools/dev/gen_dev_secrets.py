"""Generate git-ignored local keys in deploy/compose/config:

* dev-secrets.yaml: context-token and snapshot signing keys (identity, config)
* dev-service-keys.yaml: public keys of per-service identities, readable by every service (ADR 0017)
* dev-secrets-<service>.yaml: that service's private key, mounted into its group only

make dev-secrets
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from nexiqon_core.testing import make_keypair

CONFIG = Path(__file__).resolve().parents[2] / "deploy" / "compose" / "config"
OUT = CONFIG / "dev-secrets.yaml"
SERVICE_IDENTITIES = [
    "ingestion",
    "agent-runtime",
]  # services that sign their own tenant-scoped tokens


def _write(path: Path, data: dict[str, object]) -> None:
    path.write_text(
        "# Generated by tools/dev/gen_dev_secrets.py. Local development only.\n"
        + yaml.safe_dump(data)
    )
    path.chmod(0o644)  # readable by the non-root container user; local dev keys only
    print(f"wrote {path}")


def service_keys(force: bool) -> None:
    """Create a key pair for every service identity that lacks one; keep the existing ones."""
    public_file = CONFIG / "dev-service-keys.yaml"
    current = (
        (yaml.safe_load(public_file.read_text()) or {})
        if public_file.exists() and not force
        else {}
    )
    tokens = current.get("context_token", {})
    public_keys: dict[str, str] = dict(tokens.get("public_keys", {}))
    mapping: dict[str, str] = dict(tokens.get("service_keys", {}))
    changed = False
    for service in SERVICE_IDENTITIES:
        kid = f"svc-{service}-dev-1"
        secret_file = CONFIG / f"dev-secrets-{service}.yaml"
        if not force and secret_file.exists() and kid in public_keys:
            continue
        private_pem, public_pem = make_keypair()
        public_keys[kid], mapping[kid] = public_pem, service
        _write(secret_file, {"service_identity": {"key_id": kid, "private_key": private_pem}})
        changed = True
    if changed:
        _write(
            public_file, {"context_token": {"public_keys": public_keys, "service_keys": mapping}}
        )


def main() -> int:
    force = "--force" in sys.argv
    service_keys(force)
    if OUT.exists() and not force:
        print(f"{OUT} exists (use --force to rotate)")
        return 0
    private_pem, public_pem = make_keypair()
    snapshot_private, _ = make_keypair()
    data = {
        "signing": {"active_kid": "dev-1", "private_keys": {"dev-1": private_pem}},
        "context_token": {"public_keys": {"dev-1": public_pem}},
        "snapshot_signing": {
            "active_kid": "snap-dev-1",
            "private_keys": {"snap-dev-1": snapshot_private},
        },
    }
    _write(OUT, data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
