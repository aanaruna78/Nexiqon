// Generates src/generated/<service>.ts from ../../../contracts/openapi/<service>.json
import { readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "../../../../contracts/openapi");
const out = join(here, "../src/generated");
mkdirSync(out, { recursive: true });
const bin = join(here, "../node_modules/.bin/openapi-typescript");
const services = readdirSync(contracts).filter((f) => f.endsWith(".json")).sort();
for (const file of services) {
  const name = basename(file, ".json");
  execFileSync(bin, [join(contracts, file), "-o", join(out, `${name}.ts`)], { stdio: "inherit" });
}
const ident = (n) => n.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
writeFileSync(
  join(here, "../src/index.ts"),
  "// Generated by scripts/generate.mjs. Do not edit.\n" +
    services
      .map((f) => basename(f, ".json"))
      .map((n) => `export type * as ${ident(n)} from "./generated/${n}";`)
      .join("\n") +
    "\n",
);
console.log(`generated types for ${services.length} services`);
