"""Installation keys: the files the platform's groups mount (the chart's keys Secret, the
single-node bundle's keys directory). Same names everywhere:

* secrets.yaml: context-token and snapshot signing private keys (identity and config only)
* public-keys.yaml: their public halves, for every other group
* service-keys.yaml: public keys of the per-service identities (ADR 0017)
* identity-<service>.yaml: that service's private key, mounted into its group only

    nexiqon-keys /path/to/keys            # creates what is missing, never overwrites
"""

from __future__ import annotations

import argparse
import os
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

import yaml
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

# Services that sign their own tenant-scoped tokens -> the settings key their private key goes under.
SERVICE_IDENTITIES = {
    "ingestion": "service_identity",
    "agent-runtime": "service_identity",
    "tool-gateway": "service_identity",
    "channel": "channel_identity",
    "evaluation": "evaluation_identity",
    "conversation": "conversation_identity",
    "metering": "metering_identity",
    "governance": "governance_identity",
    "config-mirror": "mirror_identity",  # hybrid data plane only (DV-04)
}


def keypair() -> tuple[str, str]:
    """A P-256 key pair as PEM (private PKCS#8, public SubjectPublicKeyInfo)."""
    key = ec.generate_private_key(ec.SECP256R1())
    private = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    ).decode()
    public = (
        key.public_key()
        .public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
        .decode()
    )
    return private, public


def public_of(private_pem: str) -> str:
    key = serialization.load_pem_private_key(private_pem.encode(), password=None)
    return (
        key.public_key()
        .public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
        .decode()
    )


def _write(path: Path, data: dict[str, object], mode: int) -> None:
    path.write_text("# Generated by nexiqon-keys. Keep private.\n" + yaml.safe_dump(data))
    path.chmod(mode)


def generate(out: Path, *, mode: int = 0o640) -> list[str]:
    """Create the installation's key files in ``out``; existing files are kept. Returns the names
    written. ``public-keys.yaml`` and ``service-keys.yaml`` are always rebuilt from the private
    files, so they stay consistent."""
    out.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    stamp = datetime.now(UTC).strftime("%Y%m%d")
    secrets = out / "secrets.yaml"
    if not secrets.exists():
        token_private, token_public = keypair()
        snap_private, _ = keypair()
        kid, snap_kid = f"ctx-{stamp}", f"snap-{stamp}"
        _write(
            secrets,
            {
                "signing": {"active_kid": kid, "private_keys": {kid: token_private}},
                "context_token": {"public_keys": {kid: token_public}},
                "snapshot_signing": {
                    "active_kid": snap_kid,
                    "private_keys": {snap_kid: snap_private},
                },
            },
            mode,
        )
        written.append(secrets.name)
    data = yaml.safe_load(secrets.read_text())
    snapshot = {
        kid: public_of(pem)
        for kid, pem in (data.get("snapshot_signing") or {}).get("private_keys", {}).items()
    }
    _write(
        out / "public-keys.yaml",
        {
            "context_token": {"public_keys": data["context_token"]["public_keys"]},
            "snapshot_public_keys": snapshot,
        },
        0o644,
    )
    written.append("public-keys.yaml")

    public: dict[str, str] = {}
    owners: dict[str, str] = {}
    for service, settings_key in SERVICE_IDENTITIES.items():
        path = out / f"identity-{service}.yaml"
        if not path.exists():
            private, _ = keypair()
            kid = f"svc-{service}-{stamp}"
            _write(path, {settings_key: {"key_id": kid, "private_key": private}}, mode)
            written.append(path.name)
        ident = yaml.safe_load(path.read_text())[settings_key]
        public[ident["key_id"]] = public_of(ident["private_key"])
        owners[ident["key_id"]] = service
    _write(
        out / "service-keys.yaml",
        {"context_token": {"public_keys": public, "service_keys": owners}},
        0o644,
    )
    written.append("service-keys.yaml")
    return written


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Create an installation's signing keys")
    parser.add_argument("out", type=Path, help="directory for the key files")
    parser.add_argument(
        "--mode", default="640", help="permissions of private key files (octal, default 640)"
    )
    parser.add_argument(
        "--owner", type=int, default=None, help="give every key file to this user id (needs root)"
    )
    args = parser.parse_args(argv)
    for name in generate(args.out, mode=int(args.mode, 8)):
        print(f"wrote {os.path.join(args.out, name)}")
    if args.owner is not None:
        for path in [args.out, *args.out.glob("*.yaml")]:
            os.chown(path, args.owner, args.owner)


if __name__ == "__main__":
    main()
